"""
OpenTelemetry instrumentation for the Agentic Analytics agent — AgentCore Evaluation parity.

Generated by applying the `ac-evaluation-transform` skill. It makes the Claude Agent SDK
agent emit the SAME OTEL traces + structured I/O logs + EMF-style metrics that Strands
auto-instrumentation produces, so all 9 Amazon Bedrock AgentCore built-in evaluators
(Helpfulness, Faithfulness, Correctness, Coherence, Conciseness, Harmfulness,
InstructionFollowing, GoalSuccessRate, ToolSelectionAccuracy) can parse the agent's spans
and match them to log events.

ADAPTATION FROM THE SKILL REFERENCE (references/agent_claude_reference.py):
  The skill's reference is a standalone CLI that builds its OWN TracerProvider /
  LoggerProvider / MeterProvider + SigV4 OTLP exporters. Inside an AgentCore Runtime the
  container ALREADY launches with `opentelemetry-instrument` + the AWS distro
  (OTEL_PYTHON_DISTRO=aws_distro), which installs those providers globally with the correct
  AWS exporters, resource attributes (`cloud.resource_id`, `aws.log.group.names=…-DEFAULT`)
  and the `x-aws-log-group` OTLP header. OTEL providers are set-once, so re-creating them
  here would be dead code. Instead we REUSE the global providers via `trace.get_tracer(...)`,
  `get_logger_provider().get_logger(...)` and `metrics.get_meter(...)`. Emitting through them
  auto-routes to the right `-DEFAULT` log group that `agentcore run eval` queries.

This module changes NO agent logic, tools, or prompts. It only adds telemetry, and it
degrades to a safe no-op when observability is disabled or OTEL is unavailable (e.g. local
dev / fast tests), so the agent never crashes.
"""
from __future__ import annotations

import json
import os
import time
import uuid
from datetime import datetime, timezone

# Observability is only active inside the deployed runtime (or when explicitly asked for).
# Off by default so local `run_query()` and the credential-free fast tests are unaffected.
ENABLED = os.getenv("AGENT_OBSERVABILITY_ENABLED", "").lower() in ("1", "true", "yes")

# OTEL is optional at import time — the local dev/test venv may not have it installed.
# If any import fails we fall back to a complete no-op so agent.py still imports cleanly.
try:
    from opentelemetry import baggage, context, metrics, trace
    from opentelemetry._logs import SeverityNumber, get_logger_provider

    try:  # opentelemetry-sdk moved LogRecord across versions
        from opentelemetry.sdk._logs import LogRecord
    except ImportError:  # >= 1.40
        from opentelemetry.sdk._logs._internal import LogRecord

    _OTEL_AVAILABLE = True
except Exception:  # pragma: no cover - defensive
    _OTEL_AVAILABLE = False

ENABLED = ENABLED and _OTEL_AVAILABLE

# ---------------------------------------------------------------------------
# Configuration (derived from the runtime env — never hardcoded per account)
# ---------------------------------------------------------------------------
_MODEL_ID = os.getenv("ANTHROPIC_MODEL", "global.anthropic.claude-opus-4-6-v1")
_AGENT_NAME = os.getenv("AGENTCORE_AGENT_NAME") or os.getenv("OTEL_SERVICE_NAME") or "analytics"
_REGION = os.getenv("AWS_REGION", "us-east-1")
# The tools the agent is allowed to call (for the invoke_agent span attribute). Kept in
# sync with build_agent_options() but only used as a descriptive span attribute.
_AGENT_TOOLS = '["execute_athena_query"]'


# ---------------------------------------------------------------------------
# Providers — REUSED from the ADOT global setup (see module docstring)
# ---------------------------------------------------------------------------
if ENABLED:
    tracer = trace.get_tracer("strands.telemetry.tracer")

    _log_provider = get_logger_provider()
    _struct_logger = _log_provider.get_logger("strands.telemetry.tracer")
    _bedrock_logger = _log_provider.get_logger(
        "opentelemetry.instrumentation.botocore.bedrock-runtime",
        schema_url="https://opentelemetry.io/schemas/1.30.0",
    )

    _meter = metrics.get_meter("agent_metrics")

    _BEDROCK_ATTRS = {
        "gen_ai.system": "aws.bedrock",
        "server.address": f"bedrock-runtime.{_REGION}.amazonaws.com",
        "server.port": "443",
        "gen_ai.request.model": _MODEL_ID,
        "gen_ai.operation.name": "chat",
    }

    # Strands event_loop metrics
    _cycle_count = _meter.create_counter("strands.event_loop.cycle_count", unit="Count")
    _start_cycle = _meter.create_counter("strands.event_loop.start_cycle", unit="Count")
    _end_cycle = _meter.create_counter("strands.event_loop.end_cycle", unit="Count")
    _cycle_duration = _meter.create_histogram("strands.event_loop.cycle_duration", unit="Seconds")
    _loop_input_tokens = _meter.create_histogram("strands.event_loop.input.tokens")
    _loop_output_tokens = _meter.create_histogram("strands.event_loop.output.tokens")
    _loop_latency = _meter.create_histogram("strands.event_loop.latency", unit="Milliseconds")
    _model_ttft = _meter.create_histogram("strands.model.time_to_first_token", unit="Milliseconds")

    # Strands tool metrics
    _strands_tool_call_count = _meter.create_counter("strands.tool.call_count", unit="Count")
    _strands_tool_duration = _meter.create_histogram("strands.tool.duration", unit="Seconds")
    _strands_tool_success_count = _meter.create_counter("strands.tool.success_count", unit="Count")

    # gen_ai.client metrics
    _operation_duration = _meter.create_histogram("gen_ai.client.operation.duration", unit="Seconds")
    _token_usage = _meter.create_histogram("gen_ai.client.token.usage")  # no unit — Strands omits it
else:
    tracer = None


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _sanitize(value: str) -> str:
    """Replace surrogate characters that the OTLP exporter cannot encode."""
    return value.encode("utf-8", errors="replace").decode("utf-8")


def _iso_now() -> str:
    """Return current UTC time as an ISO-8601 string."""
    return datetime.now(timezone.utc).isoformat()


def _strip_tool_prefix(name: str) -> str:
    """Strip the ``mcp__<server>__`` prefix from MCP tool names (Strands uses plain names)."""
    return name.split("__")[-1] if "__" in name else name


def _emit_structured_log(body, attributes=None, span_context=None) -> None:
    """Emit an I/O-summary log under the ``strands.telemetry.tracer`` scope."""
    if not ENABLED:
        return
    if span_context:
        tid, sid, flags = span_context
    else:
        span = trace.get_current_span()
        span_ctx = span.get_span_context() if span else None
        tid = span_ctx.trace_id if span_ctx and span_ctx.is_valid else 0
        sid = span_ctx.span_id if span_ctx and span_ctx.is_valid else 0
        flags = span_ctx.trace_flags if span_ctx and span_ctx.is_valid else 0

    merged_attrs = dict(attributes) if attributes else {}
    merged_attrs.setdefault("event.name", "strands.telemetry.tracer")
    session_id = baggage.get_baggage("session.id")
    if session_id:
        merged_attrs["session.id"] = session_id

    record = LogRecord(
        timestamp=int(time.time_ns()),
        body=body,
        severity_number=SeverityNumber.INFO,
        severity_text="",  # Strands uses empty string, NOT "INFO"
        trace_id=tid,
        span_id=sid,
        trace_flags=flags,
        attributes=merged_attrs or None,
    )
    _struct_logger.emit(record)


def _emit_bedrock_log(body, event_name, span_context=None) -> None:
    """Emit a per-message log under the bedrock-runtime scope."""
    if not ENABLED:
        return
    if span_context:
        tid, sid, flags = span_context
    else:
        span = trace.get_current_span()
        span_ctx = span.get_span_context() if span else None
        tid = span_ctx.trace_id if span_ctx and span_ctx.is_valid else 0
        sid = span_ctx.span_id if span_ctx and span_ctx.is_valid else 0
        flags = span_ctx.trace_flags if span_ctx and span_ctx.is_valid else 0

    record = LogRecord(
        timestamp=int(time.time_ns()),
        body=body,
        severity_number=SeverityNumber.INFO,
        severity_text="",
        trace_id=tid,
        span_id=sid,
        trace_flags=flags,
        attributes={"event.name": event_name, "gen_ai.system": "aws.bedrock"},
    )
    _bedrock_logger.emit(record)


# ---------------------------------------------------------------------------
# Tool-span tracking state (hooks have no shared context — key by tool_use_id)
# ---------------------------------------------------------------------------
_tool_spans: dict = {}
_tool_start_times: dict = {}
_tool_span_contexts: dict = {}
_tool_inputs: dict = {}
_tool_results: dict = {}
_active_cycle_context = None  # parent context so tool spans share the invoke_agent traceId


# ---------------------------------------------------------------------------
# Hooks (registered by build_agent_options in agent.py)
# ---------------------------------------------------------------------------
async def pre_tool_use_hook(hook_input, tool_use_id, hook_context):
    """Open a tool span parented to the cycle context so it shares the trace."""
    if not ENABLED:
        return {}
    tool_name = hook_input["tool_name"]
    tool_input = hook_input.get("tool_input", {})

    span = tracer.start_span(
        f"tool.{tool_name}",
        context=_active_cycle_context,
        attributes={
            "tool.input": _sanitize(str(tool_input)),
            "gen_ai.tool.name": _strip_tool_prefix(tool_name),
            "gen_ai.tool.call.id": tool_use_id or "",
            "gen_ai.operation.name": "execute_tool",
            "gen_ai.event.start_time": _iso_now(),
        },
    )
    if tool_use_id:
        _tool_spans[tool_use_id] = span
        _tool_start_times[tool_use_id] = time.time()
        _tool_inputs[tool_use_id] = tool_input
    return {}


async def post_tool_use_hook(hook_input, tool_use_id, hook_context):
    """Emit the per-tool I/O summary (critical for eval) before ending the tool span."""
    if not ENABLED:
        return {}
    tool_name = hook_input.get("tool_name", "unknown")
    tool_response = hook_input.get("tool_response", "")
    plain_name = _strip_tool_prefix(tool_name)

    span = _tool_spans.pop(tool_use_id, None) if tool_use_id else None
    start_time = _tool_start_times.pop(tool_use_id, None) if tool_use_id else None
    tool_input_args = _tool_inputs.pop(tool_use_id, {}) if tool_use_id else {}
    if span:
        span.set_attribute("tool.output", _sanitize(str(tool_response)))
        span.set_attribute("gen_ai.tool.status", "success")
        span.set_attribute("gen_ai.event.end_time", _iso_now())

    saved_ctx = _tool_span_contexts.pop(tool_use_id, None) if tool_use_id else None

    # Extract plain text from the tool response content items
    result_content = []
    if isinstance(tool_response, dict) and "content" in tool_response:
        items = tool_response["content"]
    elif isinstance(tool_response, list):
        items = tool_response
    else:
        items = None
    if items is not None:
        for item in items:
            if isinstance(item, dict) and item.get("type") == "text":
                result_content.append({"text": item["text"]})
            elif isinstance(item, dict) and "text" in item:
                result_content.append({"text": item["text"]})
            else:
                result_content.append({"text": str(item)})
    else:
        result_content.append({"text": str(tool_response)})

    if tool_use_id:
        _tool_results[tool_use_id] = result_content

    # --- Per-tool I/O summary (without this the evaluator throws LogEventMissingException) ---
    if span and tool_use_id:
        tool_span_ctx = span.get_span_context()
        _emit_structured_log(
            {
                "output": {"messages": [{
                    "content": {
                        "message": json.dumps([{"text": t["text"]} for t in result_content]),
                        "id": tool_use_id,
                    },
                    "role": "assistant",
                }]},
                "input": {"messages": [{
                    "content": {
                        "content": json.dumps(tool_input_args) if tool_input_args else "{}",
                        "role": "tool",
                        "id": tool_use_id,
                    },
                    "role": "tool",
                }]},
            },
            span_context=(
                tool_span_ctx.trace_id,
                tool_span_ctx.span_id,
                tool_span_ctx.trace_flags,
            ),
        )
        span.end()
    elif span:
        span.end()

    # Bedrock-format logs
    _emit_bedrock_log(
        {"content": result_content, "id": tool_use_id or ""},
        "gen_ai.tool.message",
        span_context=saved_ctx,
    )
    _emit_bedrock_log(
        {"content": [{"toolResult": {
            "toolUseId": tool_use_id or "",
            "content": result_content,
            "status": "success",
        }}]},
        "gen_ai.user.message",
        span_context=saved_ctx,
    )

    # Tool metrics
    tool_attrs = {"tool_name": plain_name, "tool_use_id": tool_use_id or ""}
    duration = time.time() - start_time if start_time else 0
    _strands_tool_call_count.add(1, tool_attrs)
    _strands_tool_duration.record(duration, tool_attrs)
    _strands_tool_success_count.add(1, tool_attrs)
    return {}


def hooks_config():
    """Return the hooks dict for ClaudeAgentOptions, or None when disabled.

    Imported lazily inside build_agent_options so agent.py doesn't hard-depend on the SDK
    hook types at module import time.
    """
    if not ENABLED:
        return None
    from claude_agent_sdk.types import HookMatcher

    return {
        "PreToolUse": [HookMatcher(hooks=[pre_tool_use_hook])],
        "PostToolUse": [HookMatcher(hooks=[post_tool_use_hook])],
    }


# ---------------------------------------------------------------------------
# Turn driver — wraps the streaming query loop with the Strands span hierarchy
# ---------------------------------------------------------------------------
async def run_instrumented(client, user_input, *, agent_name=None, model_id=None, session_id=None):
    """Run ONE query turn against `client`, emitting the full Strands span tree + I/O
    summary, and yield the assistant's text chunks.

    Falls back to a plain stream (no telemetry) when observability is disabled, so the
    local `run_query()` path and fast tests behave identically to before.

        invoke_agent <name>            (INTERNAL, status=OK)
          └── execute_event_loop_cycle (INTERNAL)
                ├── chat               (INTERNAL)
                ├── chat <model-id>    (CLIENT)
                └── tool.<name>        (INTERNAL, from hooks)
    """
    # Lazy import so this module never hard-requires the SDK message classes at import time.
    from claude_agent_sdk import AssistantMessage, ResultMessage, TextBlock, ToolUseBlock

    if not ENABLED:
        await client.query(user_input)
        async for message in client.receive_response():
            for block in getattr(message, "content", []) or []:
                text = getattr(block, "text", None)
                if text:
                    yield text
        return

    agent_name = agent_name or _AGENT_NAME
    model_id = model_id or _MODEL_ID

    query_start = time.time()
    cycle_id = str(uuid.uuid4())
    user_input = _sanitize(user_input)

    # Put session.id into baggage so the BaggageSpanProcessor (if present) copies it onto
    # every span, and so _emit_structured_log stamps it on the I/O-summary logs. This ties
    # a session's spans together for the session-level GoalSuccessRate evaluator.
    if session_id:
        context.attach(baggage.set_baggage("session.id", session_id))

    global _active_cycle_context

    _agent_attrs = {
        "user.input": user_input,
        "gen_ai.operation.name": "invoke_agent",
        "gen_ai.system": "aws.bedrock",
        "gen_ai.agent.name": agent_name,
        "gen_ai.request.model": model_id,
        "gen_ai.agent.tools": _AGENT_TOOLS,
        "gen_ai.event.start_time": _iso_now(),
    }
    if session_id:
        _agent_attrs["session.id"] = session_id

    with tracer.start_as_current_span(
        f"invoke_agent {agent_name}",
        attributes=_agent_attrs,
    ) as agent_span:
        _start_cycle.add(1, {"event_loop_cycle_id": cycle_id})
        _cycle_count.add(1, {"event_loop_cycle_id": cycle_id})

        # Bedrock-format log: current user input
        _emit_bedrock_log({"content": [{"text": user_input}]}, "gen_ai.user.message")

        # execute_event_loop_cycle span (parent for chat + tool spans)
        cycle_span = tracer.start_span(
            "execute_event_loop_cycle", attributes={"gen_ai.event.start_time": _iso_now()}
        )
        _active_cycle_context = trace.set_span_in_context(cycle_span)
        _cycle_ctx = context.attach(_active_cycle_context)

        chat_start = time.time()
        chat_span = tracer.start_span("chat", attributes={
            "gen_ai.operation.name": "chat",
            "gen_ai.system": "aws.bedrock",
            "gen_ai.request.model": model_id,
            "gen_ai.event.start_time": _iso_now(),
        })
        client_span = tracer.start_span(
            f"chat {model_id}",
            kind=trace.SpanKind.CLIENT,
            attributes={
                "gen_ai.operation.name": "chat",
                "gen_ai.system": "aws.bedrock",
                "gen_ai.request.model": model_id,
                "gen_ai.event.start_time": _iso_now(),
            },
        )

        await client.query(user_input)

        output_messages: list = []
        last_response_text = ""
        first_token_time = None
        pending_text_blocks: list = []
        tool_use_records: list = []

        async for message in client.receive_response():
            if isinstance(message, AssistantMessage):
                for block in message.content:
                    if isinstance(block, TextBlock):
                        if first_token_time is None:
                            first_token_time = time.time()
                        pending_text_blocks.append(block.text)
                        last_response_text = block.text
                        yield block.text

                    elif isinstance(block, ToolUseBlock):
                        if first_token_time is None:
                            first_token_time = time.time()

                        # Save the current span context so post_tool_use_hook (which runs
                        # outside the OTel context) can correlate its bedrock logs.
                        _cur = trace.get_current_span()
                        if _cur and block.id:
                            _sc = _cur.get_span_context()
                            if _sc and _sc.is_valid:
                                _tool_span_contexts[block.id] = (
                                    _sc.trace_id, _sc.span_id, _sc.trace_flags,
                                )

                        plain_name = _strip_tool_prefix(block.name)
                        tool_input = block.input if hasattr(block, "input") else {}
                        assistant_content = [{"text": t} for t in pending_text_blocks]
                        assistant_content.append({"toolUse": {
                            "name": plain_name, "input": tool_input, "toolUseId": block.id,
                        }})
                        tool_call_entry = {
                            "type": "function",
                            "id": block.id,
                            "function": {"name": plain_name, "arguments": tool_input},
                        }
                        _emit_bedrock_log(
                            {"content": assistant_content, "tool_calls": [tool_call_entry]},
                            "gen_ai.assistant.message",
                        )
                        _emit_bedrock_log(
                            {"message": {"tool_calls": [tool_call_entry], "role": "assistant"},
                             "index": 0, "finish_reason": "tool_use"},
                            "gen_ai.choice",
                        )
                        tool_use_records.append({"id": block.id, "name": plain_name})
                        output_messages.append({
                            "content": {"content": json.dumps(assistant_content)},
                            "role": "assistant",
                        })
                        pending_text_blocks.clear()

            elif isinstance(message, ResultMessage):
                query_duration = time.time() - query_start
                usage = getattr(message, "usage", None) or {}

                if pending_text_blocks:
                    for t in pending_text_blocks:
                        _emit_bedrock_log({"content": [{"text": t}]}, "gen_ai.assistant.message")
                        _emit_bedrock_log(
                            {"message": {"content": [{"text": t}], "role": "assistant"},
                             "index": 0, "finish_reason": "end_turn"},
                            "gen_ai.choice",
                        )
                    output_messages.append({
                        "content": {"content": json.dumps([{"text": t} for t in pending_text_blocks])},
                        "role": "assistant",
                    })
                    pending_text_blocks.clear()

                # Enrich tool-calling output messages with their results
                for rec in tool_use_records:
                    result_content = _tool_results.pop(rec["id"], [{"text": ""}])
                    tool_result_json = json.dumps([{"toolResult": {
                        "toolUseId": rec["id"], "status": "success", "content": result_content,
                    }}])
                    for msg in output_messages:
                        c = msg.get("content", {})
                        if isinstance(c, dict) and "content" in c and rec["id"] in c.get("content", ""):
                            c["message"] = c.pop("content")
                            c["tool.result"] = tool_result_json
                            break

                # Convert the final text-only message to Strands final format
                if output_messages:
                    last = output_messages[-1]
                    c = last.get("content", {})
                    if isinstance(c, dict) and "content" in c:
                        c["message"] = c.pop("content")
                        c["finish_reason"] = "end_turn"

                # invoke_agent-level input: user message ONLY (no role:"tool")
                input_messages = [{
                    "content": {"content": json.dumps([{"text": user_input}])},
                    "role": "user",
                }]

                if usage:
                    input_tokens = usage.get("input_tokens", 0)
                    output_tokens = usage.get("output_tokens", 0)
                    total_tokens = input_tokens + output_tokens
                    usage_summary = {
                        "inputTokens": input_tokens,
                        "outputTokens": output_tokens,
                        "totalTokens": total_tokens,
                    }
                    cache_read = usage.get("cache_read_input_tokens", 0)
                    cache_write = usage.get("cache_creation_input_tokens", 0)
                    if cache_read:
                        usage_summary["cacheReadInputTokens"] = cache_read
                    if cache_write:
                        usage_summary["cacheWriteInputTokens"] = cache_write
                else:
                    usage_summary = "unavailable"  # string survives proto3 serialization
                    input_tokens = output_tokens = total_tokens = 0
                    cache_read = cache_write = 0

                _token_attrs = {
                    "gen_ai.usage.input_tokens": input_tokens,
                    "gen_ai.usage.output_tokens": output_tokens,
                    "gen_ai.usage.prompt_tokens": input_tokens,
                    "gen_ai.usage.completion_tokens": output_tokens,
                    "gen_ai.usage.total_tokens": total_tokens,
                }
                if cache_read:
                    _token_attrs["gen_ai.usage.cache_read_input_tokens"] = cache_read
                if cache_write:
                    _token_attrs["gen_ai.usage.cache_write_input_tokens"] = cache_write

                chat_end_time = time.time()
                chat_duration_s = chat_end_time - chat_start
                ttft_s = (first_token_time - chat_start) if first_token_time else chat_duration_s

                for s in (client_span, chat_span):
                    s.set_attribute("gen_ai.event.end_time", _iso_now())
                    s.set_attribute("gen_ai.server.request.duration", chat_duration_s)
                    s.set_attribute("gen_ai.server.time_to_first_token", ttft_s)
                    for k, v in _token_attrs.items():
                        s.set_attribute(k, v)
                    s.end()

                cycle_span.set_attribute("gen_ai.event.end_time", _iso_now())
                cycle_span.end()
                context.detach(_cycle_ctx)
                _active_cycle_context = None

                # I/O summary — emitted AFTER cycle detach so invoke_agent is current
                _emit_structured_log({
                    "output": {"messages": output_messages},
                    "input": {"messages": input_messages},
                    "usage": usage_summary,
                })

                for k, v in _token_attrs.items():
                    agent_span.set_attribute(k, v)
                agent_span.set_attribute("gen_ai.event.end_time", _iso_now())
                agent_span.set_status(trace.Status(trace.StatusCode.OK))

                # Metrics
                query_duration_ms = query_duration * 1000
                ttft_ms = ((first_token_time - query_start) * 1000) if first_token_time else query_duration_ms
                _end_cycle.add(1, {"event_loop_cycle_id": cycle_id})
                _cycle_duration.record(query_duration, {"event_loop_cycle_id": cycle_id})
                _loop_input_tokens.record(input_tokens)
                _loop_output_tokens.record(output_tokens)
                _loop_latency.record(query_duration_ms)
                _model_ttft.record(ttft_ms)
                _operation_duration.record(query_duration, _BEDROCK_ATTRS)
                if input_tokens:
                    _token_usage.record(input_tokens, {**_BEDROCK_ATTRS, "gen_ai.token.type": "input"})
                if output_tokens:
                    _token_usage.record(output_tokens, {**_BEDROCK_ATTRS, "gen_ai.token.type": "output"})


def shutdown() -> None:
    """Flush the global providers (traces first) so the final turn isn't lost on exit."""
    if not ENABLED:
        return
    for getter, attr in (
        (trace.get_tracer_provider, "shutdown"),
        (get_logger_provider, "shutdown"),
        (metrics.get_meter_provider, "shutdown"),
    ):
        try:
            provider = getter()
            fn = getattr(provider, attr, None)
            if callable(fn):
                fn()
        except Exception:  # pragma: no cover - best effort on shutdown
            pass
